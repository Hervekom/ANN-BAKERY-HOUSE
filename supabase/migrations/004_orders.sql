-- ANN BAKERY HOUSE — Supabase Migration 004: Orders & Order Items
-- -----------------------------------------------------------------------------
-- STATUS: PROPOSAL — NOT APPLIED. Requires explicit owner approval before it is
-- executed against the live Supabase project.
--
-- WHY THIS FILE EXISTS
--   The Sales Analytics dashboard reads real recorded orders. No order
--   persistence exists today: the storefront sends WhatsApp messages and stores
--   only a copy of the message text in the browser's localStorage. This file
--   adds the minimum order infrastructure the analytics need, without touching
--   any existing table, row or column.
--
-- DESIGN NOTES
--   * Orders are private business data: Row Level Security grants access to
--     administrators only (`app_metadata.role = 'admin'`, via public.is_admin()).
--     There is no public or customer read in this revision.
--   * Order lines store IMMUTABLE snapshots (product name, category name and the
--     selling price at purchase time). Renaming, re-pricing or deleting a product
--     afterwards never rewrites history.
--   * Prices may legitimately be NULL ("Price to be confirmed"). NULL is preserved
--     as NULL — no price is ever invented, and analytics treat unknown prices as 0
--     revenue rather than guessing.
--   * Revenue is derived ONLY from orders whose `status = 'completed'`.
--     Pending / confirmed / preparing / cancelled orders never count toward
--     revenue or units.
--
-- REVISION NOTE (order capture)
--   This revision adds the pieces required to record real customer orders while
--   keeping WhatsApp as the communication channel:
--     * `status` now includes 'preparing' (Pending → Confirmed → Preparing →
--       Completed, with Cancelled as the terminal negative state).
--     * `idempotency_key` + a partial unique index make order capture idempotent,
--       so a repeated click or a page refresh never creates a duplicate order.
--     * `order_number` is generated by a database sequence (ANN-YYYY-00001).
--     * `public.place_order(jsonb)` is a SECURITY DEFINER RPC that captures orders
--       THROUGH A TRUSTED DATABASE MECHANISM: it looks up each product's real
--       availability and price server-side, snapshots name/category/price, and
--       ignores any price submitted by the browser.
--   Direct table writes remain administrator-only; anonymous customers can only
--   call the RPC (which is the sole public write path).
--
-- Apply after 001 → 002 → 003 (or independently; it only depends on the helper
-- `public.set_updated_at()` and `public.is_admin()` defined in 001/002).
-- =============================================================================

begin;

-- =============================================================================
-- 1. orders
-- =============================================================================
-- Monotonic order numbering. The reference is produced inside the database
-- (ANN-YYYY-00001) so it is unique and never guessed or supplied by a client.
create sequence if not exists public.order_number_seq;

create table if not exists public.orders (
  id             uuid primary key default gen_random_uuid(),
  order_number   text not null unique
                   default ('ANN-' || to_char(now(), 'YYYY') || '-' ||
                            lpad(nextval('public.order_number_seq')::text, 5, '0')),
  idempotency_key text,
  customer_id    uuid references public.profiles(id) on delete set null,
  customer_name  text,
  customer_phone text,
  channel        text not null default 'whatsapp'
                   check (channel in ('whatsapp','in_person','phone','other')),
  fulfillment_method text not null default 'pickup'
                   check (fulfillment_method in ('pickup','delivery')),
  status         text not null default 'pending'
                   check (status in ('pending','confirmed','preparing','completed','cancelled')),
  payment_status text not null default 'unpaid'
                   check (payment_status in ('unpaid','paid','refunded')),
  currency       text not null default 'PHP',
  subtotal_php   numeric(12,2) check (subtotal_php is null or subtotal_php >= 0),
  total_php      numeric(12,2) check (total_php is null or total_php >= 0),
  notes          text,
  placed_at      timestamptz not null default now(),
  completed_at   timestamptz,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

comment on table public.orders is
  'Recorded sales orders. Revenue is derived ONLY from rows with status = ''completed''.';
comment on column public.orders.order_number is
  'Human-readable reference shown to the customer (ANN-YYYY-00001), generated by a database sequence.';
comment on column public.orders.idempotency_key is
  'Client-supplied retry key. Unique when present, so a repeated submit or refresh returns the same order instead of duplicating it.';
comment on column public.orders.customer_id is
  'Optional link to a registered profile; guest / WhatsApp orders keep only the name + phone snapshot.';
comment on column public.orders.total_php is
  'Order total in PHP. NULL means a line price is still "to be confirmed" — never invented.';
comment on column public.orders.payment_status is
  'Payment state for auditability. Analytics key off status = ''completed'', not this column.';

create index if not exists orders_placed_at_idx on public.orders (placed_at desc);
create index if not exists orders_status_idx     on public.orders (status);
create index if not exists orders_customer_idx   on public.orders (customer_id);

-- Duplicate protection: at most one order per idempotency key. NULL keys are
-- excluded so administrator-created orders are unaffected.
create unique index if not exists orders_idempotency_key_idx
  on public.orders (idempotency_key)
  where idempotency_key is not null;

create trigger trg_orders_updated_at
  before update on public.orders
  for each row execute function public.set_updated_at();

-- =============================================================================
-- 2. order_items — immutable line snapshots
-- =============================================================================
create table if not exists public.order_items (
  id              uuid primary key default gen_random_uuid(),
  order_id        uuid not null references public.orders(id) on delete cascade,
  product_id      uuid references public.products(id) on delete set null,
  product_name    text not null check (char_length(trim(product_name)) between 1 and 160),
  product_slug    text,
  category_id     uuid references public.categories(id) on delete set null,
  category_name   text,
  unit_price_php  numeric(12,2) check (unit_price_php is null or unit_price_php >= 0),
  quantity        integer not null check (quantity > 0),
  line_total_php  numeric(12,2) check (line_total_php is null or line_total_php >= 0),
  selected_option text,
  created_at      timestamptz not null default now()
);

comment on table public.order_items is
  'Immutable order lines. Product/category names and prices are snapshotted at purchase time.';
comment on column public.order_items.product_name is
  'Snapshot of the product name at purchase time (the product may be renamed or deleted later).';
comment on column public.order_items.unit_price_php is
  'Selling price at purchase time. NULL means the price was still to be confirmed.';
comment on column public.order_items.line_total_php is
  'unit_price_php * quantity. NULL when the unit price was unknown.';

create index if not exists order_items_order_idx   on public.order_items (order_id);
create index if not exists order_items_product_idx on public.order_items (product_id);

-- =============================================================================
-- 3. Row Level Security — private business data, administrators only
-- =============================================================================
alter table public.orders      enable row level security;
alter table public.order_items enable row level security;

create policy orders_select_admin on public.orders
  for select using (public.is_admin());
create policy orders_insert_admin on public.orders
  for insert with check (public.is_admin());
create policy orders_update_admin on public.orders
  for update using (public.is_admin()) with check (public.is_admin());
create policy orders_delete_admin on public.orders
  for delete using (public.is_admin());

create policy order_items_select_admin on public.order_items
  for select using (public.is_admin());
create policy order_items_insert_admin on public.order_items
  for insert with check (public.is_admin());
create policy order_items_update_admin on public.order_items
  for update using (public.is_admin()) with check (public.is_admin());
create policy order_items_delete_admin on public.order_items
  for delete using (public.is_admin());

-- =============================================================================
-- 4. place_order() — trusted, server-side order capture (public write path)
-- =============================================================================
-- The storefront never inserts into `orders`/`order_items` directly (those tables
-- stay administrator-only). Customers call this SECURITY DEFINER function, which:
--   * runs with the owner's privileges, so it can write past RLS;
--   * validates the payload (cart not empty, quantities in range);
--   * looks up each product name/category/price and availability IN THE DATABASE
--     — any price supplied by the browser is IGNORED;
--   * snapshots name / variant / unit price onto the order line;
--   * is idempotent on `idempotency_key` (a repeated submit returns the existing
--     order instead of creating a duplicate);
--   * returns the customer-facing order reference.
-- Totals are NULL when any line price is unknown ("Price to be confirmed"), so no
-- misleading total is ever produced.
create or replace function public.place_order(payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_items         jsonb;
  v_item          jsonb;
  v_name          text;
  v_phone         text;
  v_notes         text;
  v_channel       text;
  v_fulfillment   text;
  v_idem          text;
  v_customer_id   uuid;
  v_existing      public.orders%rowtype;
  v_order         public.orders%rowtype;
  v_product       public.products%rowtype;
  v_category_name text;
  v_slug          text;
  v_qty           integer;
  v_option        text;
  v_unit          numeric(12,2);
  v_line          numeric(12,2);
  v_subtotal      numeric(12,2) := 0;
  v_all_priced    boolean := true;
  v_count         integer := 0;
begin
  if payload is null or jsonb_typeof(payload) <> 'object' then
    raise exception 'Invalid order payload.' using errcode = '22023';
  end if;

  v_items := payload -> 'items';
  if v_items is null or jsonb_typeof(v_items) <> 'array' or jsonb_array_length(v_items) = 0 then
    raise exception 'Your cart is empty. Add at least one item before ordering.' using errcode = '22023';
  end if;
  if jsonb_array_length(v_items) > 50 then
    raise exception 'Too many different items in a single order. Please contact the bakery.' using errcode = '22023';
  end if;

  v_name    := nullif(btrim(coalesce(payload ->> 'customer_name', '')), '');
  v_phone   := nullif(btrim(coalesce(payload ->> 'customer_phone', '')), '');
  v_notes   := nullif(btrim(coalesce(payload ->> 'notes', '')), '');
  v_channel := coalesce(nullif(btrim(payload ->> 'channel'), ''), 'whatsapp');
  if v_channel not in ('whatsapp','in_person','phone','other') then
    v_channel := 'whatsapp';
  end if;

  v_fulfillment := lower(coalesce(nullif(btrim(payload ->> 'fulfillment_method'), ''), 'pickup'));
  if v_fulfillment not in ('pickup','delivery') then
    v_fulfillment := 'pickup';
  end if;

  v_idem := nullif(btrim(coalesce(payload ->> 'idempotency_key', '')), '');
  if v_idem is not null then
    v_idem := left(v_idem, 100);
    -- Duplicate protection (fast path): the same checkout attempt already
    -- produced an order — return it instead of recording a second one.
    select * into v_existing from public.orders where idempotency_key = v_idem;
    if found then
      return jsonb_build_object(
        'id', v_existing.id,
        'order_number', v_existing.order_number,
        'status', v_existing.status,
        'total_php', v_existing.total_php,
        'placed_at', v_existing.placed_at,
        'duplicate', true
      );
    end if;
  end if;

  -- Link the order to a registered profile when the caller is signed in.
  -- Guests (anonymous checkout) keep only the name + phone snapshot.
  if auth.uid() is not null then
    select p.id into v_customer_id from public.profiles p where p.id = auth.uid();
  end if;

  -- Insert the header first so the line items can reference it. Totals are
  -- written after the lines are validated (all inside this transaction).
  insert into public.orders
    (idempotency_key, customer_id, customer_name, customer_phone, channel, fulfillment_method, notes)
  values
    (v_idem, v_customer_id, v_name, v_phone, v_channel, v_fulfillment, v_notes)
  on conflict (idempotency_key) where idempotency_key is not null do nothing
  returning * into v_order;

  if v_order.id is null then
    -- Race: a concurrent identical request won. Return the winning order.
    select * into v_order from public.orders where idempotency_key = v_idem;
    if not found then
      raise exception 'Unable to record the order. Please try again.' using errcode = 'P0001';
    end if;
    return jsonb_build_object(
      'id', v_order.id,
      'order_number', v_order.order_number,
      'status', v_order.status,
      'total_php', v_order.total_php,
      'placed_at', v_order.placed_at,
      'duplicate', true
    );
  end if;

  for v_item in select * from jsonb_array_elements(v_items) loop
    v_slug   := nullif(btrim(coalesce(v_item ->> 'product_slug', '')), '');
    v_qty    := coalesce((v_item ->> 'quantity')::integer, 0);
    v_option := nullif(btrim(coalesce(v_item ->> 'selected_option', '')), '');

    if v_slug is null then
      raise exception 'An order item is missing its product reference.' using errcode = '22023';
    end if;
    if v_qty < 1 or v_qty > 999 then
      raise exception 'Invalid quantity for "%".', v_slug using errcode = '22023';
    end if;

    select * into v_product from public.products where slug = v_slug;
    if not found then
      raise exception 'The product "%" is no longer on the menu. Please remove it and try again.', v_slug
        using errcode = 'P0002';
    end if;
    if v_product.is_available is not true then
      raise exception 'The product "%" is currently unavailable. Please remove it or contact the bakery.', v_product.name
        using errcode = 'P0002';
    end if;

    select c.name into v_category_name from public.categories c where c.id = v_product.category_id;

    v_unit := v_product.price_php;  -- authoritative price, read from the database
    if v_unit is null then
      v_line := null;
      v_all_priced := false;
    else
      v_line := round(v_unit * v_qty, 2);
      v_subtotal := v_subtotal + v_line;
    end if;

    insert into public.order_items
      (order_id, product_id, product_name, product_slug, category_id, category_name,
       unit_price_php, quantity, line_total_php, selected_option)
    values
      (v_order.id, v_product.id, v_product.name, v_product.slug, v_product.category_id, v_category_name,
       v_unit, v_qty, v_line, v_option);

    v_count := v_count + 1;
  end loop;

  if v_count = 0 then
    raise exception 'Your cart is empty. Add at least one item before ordering.' using errcode = '22023';
  end if;

  -- Honest totals: when ANY line price is unknown the whole total stays NULL
  -- rather than reporting a partial figure that could mislead the customer.
  update public.orders
    set subtotal_php = case when v_all_priced then v_subtotal else null end,
        total_php    = case when v_all_priced then v_subtotal else null end
    where id = v_order.id
    returning * into v_order;

  return jsonb_build_object(
    'id', v_order.id,
    'order_number', v_order.order_number,
    'status', v_order.status,
    'total_php', v_order.total_php,
    'placed_at', v_order.placed_at,
    'duplicate', false
  );
end;
$$;

comment on function public.place_order(jsonb) is
  'Trusted server-side order capture. Reads product availability and price from the database '
  '(browser-supplied prices are ignored), snapshots names/categories/prices, is idempotent on '
  'idempotency_key, and returns the customer-facing order reference. The only public write path.';

grant execute on function public.place_order(jsonb) to anon, authenticated;

commit;

